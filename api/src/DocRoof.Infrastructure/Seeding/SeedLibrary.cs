    private static readonly Dictionary<string, byte[]> Cache = new();

    /// <summary>Generated bytes are cached per process so each new tenant only copies them.</summary>
    private static Func<byte[]> Cached(string key, Func<byte[]> factory) => () =>
    {
        lock (Cache)
        {
            if (!Cache.TryGetValue(key, out var bytes))
            {
                bytes = factory();
                Cache[key] = bytes;
            }

            return bytes;
        }
    };

    private static Func<byte[]> Pdf(string key, string number, string title, string discipline, string rev, string date, string project, params SyntheticPage[] pages) =>
        Cached(key, () => SyntheticPdf.Build(new SyntheticPdfSpec(number, title, discipline, rev, date, project, pages)));

    private static Func<byte[]> Text(string key, string content) => Cached(key, () => System.Text.Encoding.UTF8.GetBytes(content.Replace("\r\n", "\n")));

